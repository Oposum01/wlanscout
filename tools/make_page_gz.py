"""
Packs the web page for the firmware: source/wlanscout/index_html.h
stays the one place the page is edited, this writes the gzip copy the
sensor serves, source/wlanscout/index_html_gz.h. About a quarter of
the size, so the page loads that much faster over Ethernet and takes
less flash.

Usage:
    python3 tools/make_page_gz.py

Run it after every change to index_html.h. The sketch compares the
length of the page with the one recorded here and refuses to build
when they differ; tests/test_page_gz.py checks the contents as well.
The output is the same for the same page (no time stamp in it).
"""

import gzip
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SKETCH = ROOT / "source" / "wlanscout"


def page_bytes():
    source = (SKETCH / "index_html.h").read_text(encoding="utf-8")
    match = re.search(r'R"HTML\((.*?)\)HTML"', source, re.S)

    if not match:
        sys.exit("no R\"HTML(...)HTML\" block in index_html.h")

    return match.group(1).encode("utf-8")


def header(page):
    packed = gzip.compress(page, compresslevel=9, mtime=0)

    lines = [
        "// Generated by tools/make_page_gz.py from index_html.h, do not",
        "// edit: change index_html.h and run the script again.",
        "//",
        "// SPDX-License-Identifier: GPL-2.0-only WITH "
        "AdditionRef-wlanscout-linking-exception",
        "// SPDX-FileCopyrightText: 2026 Dr.-Ing. Simon Wunderlich "
        "Systementwicklung & Beratung",
        "// SPDX-FileContributor: Jan Fuchs <jf [at] simonwunderlich . de>",
        "",
        "#ifndef INDEX_HTML_GZ_H",
        "#define INDEX_HTML_GZ_H",
        "",
        "// sizeof(INDEX_HTML) of the page packed here",
        "#define INDEX_HTML_SOURCE_SIZE %d" % (len(page) + 1),
        "",
        "const uint8_t INDEX_HTML_GZ[] PROGMEM = {",
    ]

    for i in range(0, len(packed), 16):
        lines.append("    " + ", ".join("0x%02x" % b
                                         for b in packed[i:i + 16]) + ",")

    lines += ["};", "", "#endif // INDEX_HTML_GZ_H", ""]

    return "\n".join(lines), len(packed)


def main():
    page = page_bytes()
    text, size = header(page)

    (SKETCH / "index_html_gz.h").write_text(text, encoding="utf-8")

    print("index_html_gz.h: %d bytes of page packed to %d" % (len(page), size))


if __name__ == "__main__":
    main()
