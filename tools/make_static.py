"""
Builds the static copy of the web page: the page the sensor serves,
for any https web space, e.g. GitHub Pages. Opened there in Chrome it
talks to a sensor on the phone's USB-C port over WebUSB (see
docs/usb.md), and Chrome offers to install it as an app that also
starts offline.

Usage:
    python3 tools/make_static.py OUTDIR [--page app.html]
                                 [--firmware BUILDDIR [--parts-dir DIR]]

Writes into OUTDIR:
    index.html (or --page)    the page from index_html.h
    manifest.webmanifest      name, icons, standalone display
    sw.js                     service worker: keeps the files for
                              offline use, renewed with every
                              firmware version
    favicon.svg, icon-192.png, icon-512.png

With --firmware (the Arduino build directory, e.g. the one given
to arduino-cli --build-path) also the flasher:
    flash.html                writes the firmware to a board on the
                              phone's USB-C port (esptool-js)
    wlanscout.ino.bootloader.bin, wlanscout.ino.partitions.bin,
    boot_app0.bin, wlanscout.ino.bin
                              the parts, each to its own address;
                              not merged.bin, which is padded to the
                              full flash and would wipe settings
                              and the IE catalog
With --parts-dir the flasher loads the parts from that folder, given
relative to OUTDIR, and they are not copied (tools/make_release.py puts
them in firmware/).
The flasher needs a network (esptool-js and the firmware are not
kept by the service worker).

The page itself is the same; only the static copy gets the manifest
link and the service worker, the sensor's own page stays as it is.
"""

import argparse
import glob
import json
import pathlib
import re
import shutil
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent

# The Arduino sketch: its folder has to carry the sketch's name
SKETCH = ROOT / "source" / "wlanscout"

# Matches the page header and background
THEME_COLOR = "#1c1c1c"
BACKGROUND_COLOR = "#111111"


def page_html():
    source = (SKETCH / "index_html.h").read_text(encoding="utf-8")
    match = re.search(r'R"HTML\((.*?)\)HTML"', source, re.S)

    if not match:
        sys.exit("no R\"HTML(...)HTML\" block in index_html.h")

    return match.group(1)


def firmware_version():
    source = (SKETCH / "wlanscout.ino").read_text(encoding="utf-8")
    match = re.search(r'#define FW_VERSION "([^"]+)"', source)

    if not match:
        sys.exit("no FW_VERSION in wlanscout.ino")

    return match.group(1)


def static_page(html):
    old_icon = '<link rel="icon" type="image/svg+xml" href="/favicon.svg">'

    if old_icon not in html:
        sys.exit("favicon link not found in the page")

    head = "\n".join([
        '<link rel="icon" type="image/svg+xml" href="favicon.svg">',
        '<link rel="manifest" href="manifest.webmanifest">',
        '<link rel="apple-touch-icon" href="icon-192.png">',
        '<meta name="theme-color" content="%s">' % THEME_COLOR,
    ])

    html = html.replace(old_icon, head)

    register = """
<script>
// Static copy only: keeps the page for offline use
if ("serviceWorker" in navigator)
    navigator.serviceWorker.register("sw.js").catch(() => { });
</script>
"""

    if "</body>" not in html:
        sys.exit("</body> not found in the page")

    return html.replace("</body>", register + "</body>", 1)


def manifest(page):
    return {
        "name": "wlanscout+",
        "short_name": "wlanscout+",
        "description": "Wi-Fi, BLE and 802.15.4 scanner on an ESP32-C5, "
                       "over USB",
        "start_url": "./" + page,
        "scope": "./",
        "display": "standalone",
        "background_color": BACKGROUND_COLOR,
        "theme_color": THEME_COLOR,
        "icons": [
            {"src": "icon-192.png", "sizes": "192x192", "type": "image/png"},
            {"src": "icon-512.png", "sizes": "512x512", "type": "image/png"},
            {"src": "favicon.svg", "sizes": "any", "type": "image/svg+xml"},
        ],
    }


def service_worker(version, files):
    return """// wlanscout static copy: the files kept for offline use.
// Generated by tools/make_static.py for firmware %(version)s; a new
// version gets a new cache and the old one is dropped.

const CACHE = "wlanscout-%(version)s";
const FILES = %(files)s;

self.addEventListener("install", event =>
{
    event.waitUntil(caches.open(CACHE)
        .then(cache => cache.addAll(FILES))
        .then(() => self.skipWaiting()));
});

self.addEventListener("activate", event =>
{
    event.waitUntil(caches.keys()
        .then(keys => Promise.all(keys
            .filter(k => k.startsWith("wlanscout-") && k !== CACHE)
            .map(k => caches.delete(k))))
        .then(() => self.clients.claim()));
});

// From the cache first, so it starts without a network; anything
// else (other files on the same site) goes to the network
self.addEventListener("fetch", event =>
{
    if (event.request.method !== "GET")
        return;

    event.respondWith(caches.match(event.request, { ignoreSearch: true })
        .then(hit => hit || fetch(event.request)));
});
""" % {"version": version, "files": json.dumps(["./" + f for f in files])}


FIRMWARE_PARTS = ["wlanscout.ino.bootloader.bin",
                  "wlanscout.ino.partitions.bin",
                  "wlanscout.ino.bin"]


def boot_app0():
    """boot_app0.bin of the installed esp32 core: the empty OTA data
    that makes the board start the firmware in the first slot."""
    found = sorted(glob.glob(str(pathlib.Path.home() /
        ".arduino15/packages/esp32/hardware/esp32/*/tools/partitions/"
        "boot_app0.bin")))

    if not found:
        sys.exit("boot_app0.bin not found in ~/.arduino15; give "
                 "--boot-app0")

    return pathlib.Path(found[-1])


def add_flasher(out, build, version, boot, parts_dir=None):
    for name in FIRMWARE_PARTS:
        if not (build / name).is_file():
            sys.exit("%s missing in %s" % (name, build))

    if version.encode() not in (build / "wlanscout.ino.bin").read_bytes():
        sys.exit("wlanscout.ino.bin in %s is not v%s: build it first"
                 % (build, version))

    # Next to the page, unless they have a folder of their own
    if not parts_dir:
        for name in FIRMWARE_PARTS:
            shutil.copyfile(build / name, out / name)

        shutil.copyfile(boot, out / "boot_app0.bin")

    page = (ROOT / "tools" / "static" / "flash.html").read_text(
        encoding="utf-8")

    page = page.replace("@VERSION@", version).replace(
        "@PARTS_DIR@", parts_dir.rstrip("/") + "/" if parts_dir else "")

    (out / "flash.html").write_text(page, encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("outdir")
    parser.add_argument("--page", default="index.html",
                        help="file name of the page (default index.html)")
    parser.add_argument("--firmware", metavar="BUILDDIR",
                        help="Arduino build directory: add the flasher "
                             "and the firmware")
    parser.add_argument("--boot-app0", metavar="FILE",
                        help="boot_app0.bin (default: from the installed "
                             "esp32 core)")
    parser.add_argument("--parts-dir", metavar="DIR",
                        help="the flasher loads the parts from DIR, "
                             "relative to OUTDIR, instead of copies "
                             "next to it")
    args = parser.parse_args()

    out = pathlib.Path(args.outdir)
    out.mkdir(parents=True, exist_ok=True)

    version = firmware_version()
    images = ROOT / "docs" / "images"

    (out / args.page).write_text(static_page(page_html()), encoding="utf-8")

    (out / "manifest.webmanifest").write_text(
        json.dumps(manifest(args.page), indent=2) + "\n", encoding="utf-8")

    shutil.copyfile(images / "favicon.svg", out / "favicon.svg")
    shutil.copyfile(images / "favicon-192.png", out / "icon-192.png")
    shutil.copyfile(images / "favicon-512.png", out / "icon-512.png")

    files = [args.page, "manifest.webmanifest", "favicon.svg",
             "icon-192.png", "icon-512.png"]

    (out / "sw.js").write_text(service_worker(version, files),
                               encoding="utf-8")

    print("static copy of v%s in %s: %s, sw.js" %
          (version, out, ", ".join(files)))

    if args.firmware:
        boot = pathlib.Path(args.boot_app0) if args.boot_app0 else boot_app0()

        add_flasher(out, pathlib.Path(args.firmware), version, boot,
                    args.parts_dir)

        print("flasher: flash.html, parts %s" %
              ("in " + args.parts_dir if args.parts_dir else
               ", ".join(FIRMWARE_PARTS) + ", boot_app0.bin"))


if __name__ == "__main__":
    main()
